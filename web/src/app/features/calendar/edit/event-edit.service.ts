import { HttpContext } from '@angular/common/http';
import { inject, Injectable } from '@angular/core';
import {
  Api,
  createEvent,
  CreateEventRequest,
  deleteEvent,
  EventPatchRequest,
  EventResponse,
  getEvent,
  listEventOccurrences,
  OccurrenceResponse,
  updateEvent,
} from '../../../api/generated';
import { ApiError, SILENT_ERRORS } from '../../../core/http';

/** Which occurrences of a series a change applies to (SPEC.md §6.2). */
export type EditScope = 'THIS' | 'FOLLOWING' | 'ALL';

/** What a change addresses: the event id, its version and, for a series, scope and occurrence. */
interface Target {
  readonly id: string;
  readonly version: number;
  readonly scope?: EditScope;
  readonly occurrence?: string;
}

/**
 * Whether `error` means the event changed since it was shown: a stale ETag (412), or a conflict
 * (409), which includes "changed at the provider" (the server fetched the new version, SPEC.md §6.2).
 */
export function isConflict(error: unknown): boolean {
  return error instanceof ApiError && (error.status === 409 || error.status === 412);
}

/** Whether `occurrence` belongs to a recurring series (a change needs a scope). */
export function isSeries(occurrence: OccurrenceResponse): boolean {
  return !!occurrence.seriesId && !!occurrence.occurrence;
}

/** Whether `occurrence` is generated by the rule of its series master (no override replaces it). */
export function isGenerated(occurrence: OccurrenceResponse): boolean {
  return isSeries(occurrence) && occurrence.eventId === occurrence.seriesId;
}

/**
 * The event requests of the calendar editor. Errors are silent (no toast): the dialog shows them
 * next to the form, the views as a message with a reload action.
 *
 * A change of an occurrence goes to the event that holds it, with that event's version as
 * If-Match: a single event or an override directly (an override with `?scope=`, it stands for its
 * occurrence), a generated occurrence to the series master with `?scope=&occurrence=`.
 */
@Injectable({ providedIn: 'root' })
export class EventEditService {
  private readonly api = inject(Api);

  get(id: string): Promise<EventResponse> {
    return this.api.invoke(getEvent, { id }, silent());
  }

  create(body: CreateEventRequest): Promise<EventResponse> {
    return this.api.invoke(createEvent, { body }, silent());
  }

  /**
   * The current state of the generated `occurrence` (it may have become an override since), or
   * `undefined` when its series no longer has it.
   */
  async reread(occurrence: OccurrenceResponse): Promise<OccurrenceResponse | undefined> {
    const { from, to } = rangeAround(occurrence);
    const { items } = await this.api.invoke(
      listEventOccurrences,
      { from, to, calendarIds: [occurrence.calendarId] },
      silent(),
    );
    return items.find(
      (item) => item.seriesId === occurrence.seriesId && item.occurrence === occurrence.occurrence,
    );
  }

  /** Changes `occurrence` (and, by `scope`, other occurrences of its series). */
  update(
    occurrence: OccurrenceResponse,
    scope: EditScope | undefined,
    body: EventPatchRequest,
  ): Promise<EventResponse> {
    const target = this.target(occurrence, scope);
    return this.api.invoke(
      updateEvent,
      {
        id: target.id,
        scope: target.scope,
        occurrence: target.occurrence,
        'If-Match': etag(target.version),
        body,
      },
      silent(),
    );
  }

  /** Deletes `occurrence` (and, by `scope`, other occurrences of its series). */
  async delete(occurrence: OccurrenceResponse, scope: EditScope | undefined): Promise<void> {
    const target = this.target(occurrence, scope);
    await this.api.invoke(
      deleteEvent,
      {
        id: target.id,
        scope: target.scope,
        occurrence: target.occurrence,
        'If-Match': etag(target.version),
      },
      silent(),
    );
  }

  private target(occurrence: OccurrenceResponse, scope: EditScope | undefined): Target {
    if (!isSeries(occurrence)) return { id: occurrence.eventId, version: occurrence.version };
    const effective = scope ?? 'THIS';
    // An override stands for its occurrence, for every scope: the server checks its own version.
    if (!isGenerated(occurrence)) {
      return { id: occurrence.eventId, version: occurrence.version, scope: effective };
    }
    return {
      id: occurrence.seriesId!,
      version: occurrence.version,
      scope: effective,
      occurrence: occurrence.occurrence,
    };
  }
}

const DAY_MS = 86_400_000;

/** A range sure to contain the occurrence originally starting at `occurrence.occurrence`. */
function rangeAround(occurrence: OccurrenceResponse): { from: string; to: string } {
  const original = occurrence.occurrence!;
  // All-day series: a date, counted by the days in the user's zone (at most a day off UTC).
  const start = original.length === 10 ? `${original}T00:00:00Z` : original;
  const at = new Date(start).getTime();
  return {
    from: new Date(at - DAY_MS).toISOString(),
    to: new Date(at + (original.length === 10 ? 2 : 1) * DAY_MS).toISOString(),
  };
}

function etag(version: number): string {
  return `"${version}"`;
}

function silent(): HttpContext {
  return new HttpContext().set(SILENT_ERRORS, true);
}
